"""
Validation and output verification utilities.

Provides:
- validate_outputs(): validates internal matches DataFrame against candidate pairs
  enforcing candidate freezing, single-row-per-S1, and subset invariants.
"""
from __future__ import annotations

import logging
from typing import Any

import pandas as pd

logger = logging.getLogger(__name__)


def validate_outputs(
    matches: pd.DataFrame,
    candidate_pairs: pd.DataFrame,
    raise_on_error: bool = True,
) -> bool:
    """
    Validate that model matching decisions satisfy all system invariants:
    1. Exactly one row per unique Source 1 entity.
    2. No NaN / null entity IDs.
    3. Candidate freezing / subset invariant: All predicted match IDs must be
       members of the candidate set generated by the blocking stage for that S1 entity.

    Parameters
    ----------
    matches : pd.DataFrame
        Matches DataFrame (either internal format with 's1_id', 's2_id', 's3_id'
        or export format with 'source1_entity_id', 'matched_entity_ids').
    candidate_pairs : pd.DataFrame
        Candidate pairs generated by blocking stage.
    raise_on_error : bool
        If True, raises ValueError on any violation. If False, logs error and returns False.

    Returns
    -------
    bool
        True if all invariants pass.

    Raises
    ------
    ValueError
        If any validation check fails and raise_on_error is True.
    """
    errors: list[str] = []

    # 1. Determine S1 column name
    s1_col = "source1_entity_id" if "source1_entity_id" in matches.columns else "s1_id"
    if s1_col not in matches.columns:
        errors.append(f"Matches DataFrame missing S1 ID column ('s1_id' or 'source1_entity_id'). Found: {list(matches.columns)}")
        if raise_on_error:
            raise ValueError("; ".join(errors))
        return False

    # 2. Check for duplicate S1 rows
    dup_s1 = matches[s1_col].duplicated().sum()
    if dup_s1 > 0:
        errors.append(f"Matches contains {dup_s1} duplicate rows for {s1_col}.")

    # 3. Check for null / NaN in S1 IDs
    null_s1 = matches[s1_col].isna().sum()
    if null_s1 > 0:
        errors.append(f"Matches contains {null_s1} null/NaN values in {s1_col}.")

    # 4. Build candidate set lookup per S1 entity
    cand_s1_col = "source1_entity_id" if "source1_entity_id" in candidate_pairs.columns else "s1_id"
    cand_dict: dict[str, set[str]] = {}

    def _extract_cands(row: pd.Series) -> list[str]:
        if "candidate_entity_ids" in row:
            raw = row["candidate_entity_ids"]
            if isinstance(raw, str) and raw.strip():
                return [x.strip() for x in raw.split(",") if x.strip()]
            return []
        cands = []
        for col in ("candidate_entity_id", "s2_id", "s3_id"):
            val = row.get(col)
            if val and not pd.isna(val) and str(val).strip():
                cands.append(str(val).strip())
        return cands

    for _, row in candidate_pairs.iterrows():
        s1 = str(row[cand_s1_col]).strip()
        if s1 not in cand_dict:
            cand_dict[s1] = set()
        cand_dict[s1].update(_extract_cands(row))

    # 5. Check candidate subset invariant
    def _extract_matches(row: pd.Series) -> list[str]:
        if "matched_entity_ids" in row:
            raw = row["matched_entity_ids"]
            if isinstance(raw, (set, list)):
                return [str(x).strip() for x in raw if str(x).strip()]
            if isinstance(raw, str) and raw.strip():
                return [x.strip() for x in raw.split(",") if x.strip()]
            return []
        m = []
        for col in ("s2_id", "s3_id"):
            val = row.get(col)
            if isinstance(val, (set, list)):
                m.extend(str(x).strip() for x in val if str(x).strip())
            elif val and not pd.isna(val) and str(val).strip():
                m.extend(x.strip() for x in str(val).split(",") if x.strip())
        return m

    subset_violations = 0
    for _, row in matches.iterrows():
        s1 = str(row[s1_col]).strip()
        matched_ids = _extract_matches(row)
        valid_cands = cand_dict.get(s1, set())
        for mid in matched_ids:
            if mid not in valid_cands:
                subset_violations += 1
                if subset_violations <= 5:
                    errors.append(
                        f"Candidate subset violation: matched ID '{mid}' for S1 '{s1}' was not in candidate set."
                    )

    if subset_violations > 5:
        errors.append(f"Total candidate subset violations: {subset_violations}.")

    if errors:
        msg = f"Validation failed with {len(errors)} error(s):\n" + "\n".join(errors)
        logger.error(msg)
        if raise_on_error:
            raise ValueError(msg)
        return False

    logger.info("Validation successful: %d records satisfy all invariants.", len(matches))
    return True
